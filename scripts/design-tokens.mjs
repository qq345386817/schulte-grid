import { readFile } from 'node:fs/promises';

export async function buildTokens() {
  const tokens = JSON.parse(await readFile(new URL('../style/tokens.json', import.meta.url), 'utf8'));
  const colors = theme => tokens.color.tokens.map(token => `  --${token.name}: ${token.value[theme]};`).join('\n');
  const dimensions = ['spacing', 'radius'].flatMap(family => tokens[family].tokens.map(token => `  --${token.name}: ${token.value};`));
  const typography = tokens.type.groups.flatMap(group => group.styles.flatMap(style => [
    `  --${style.name}-size: ${style.fontSize};`,
    `  --${style.name}-line: ${style.lineHeight};`,
    `  --${style.name}-weight: ${style.fontWeight};`
  ]));
  return `/* Generated by npm run build from style/tokens.json. */
:root {
${colors('light')}
${dimensions.join('\n')}
${typography.join('\n')}
  --surface: var(--surface-strong);
  --font-sans: ${tokens.type.families.sans};
}
@media (prefers-color-scheme: dark) {
  :root {
${colors('dark')}
  }
}
html[data-theme] {
  --surface-soft: #edf2f7;
  --control-border: #7a8797;
  --on-primary: #ffffff;
  --mint: #087b60;
  --mint-soft: #e5f4ef;
  --next-bg: #fff3d6;
  --next-ink: #77420c;
}
html[data-theme="night"] {
${colors('dark')}
}
`;
}
