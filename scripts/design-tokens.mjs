import { readFile } from 'node:fs/promises';

export async function buildTokens() {
  const tokens = JSON.parse(await readFile(new URL('../style/tokens.json', import.meta.url), 'utf8'));
  const colors = theme => tokens.color.tokens.map(token => `  --${token.name}: ${token.value[theme]};`).join('\n');
  const dimensions = ['spacing', 'radius'].flatMap(family => tokens[family].tokens.map(token => `  --${token.name}: ${token.value};`));
  const typography = tokens.type.groups.flatMap(group => group.styles.flatMap(style => [
    `  --${style.name}-size: ${style.fontSize};`,
    `  --${style.name}-line: ${style.lineHeight};`,
    `  --${style.name}-weight: ${style.fontWeight};`
  ]));
  const lightElevation = [
    '  --glass-bg: rgba(246, 247, 249, 0.82);',
    '  --glass-border: rgba(16, 24, 40, 0.08);',
    '  --card-border: rgba(16, 24, 40, 0.08);',
    '  --shadow-xs: 0 1px 2px rgba(16, 24, 40, 0.05);',
    '  --shadow-sm: 0 2px 6px rgba(16, 24, 40, 0.05), 0 1px 2px rgba(16, 24, 40, 0.04);',
    '  --shadow-md: 0 12px 30px -10px rgba(16, 24, 40, 0.10), 0 2px 6px rgba(16, 24, 40, 0.04);',
    '  --shadow-stage: 0 28px 64px -22px rgba(16, 24, 40, 0.14), 0 4px 14px rgba(16, 24, 40, 0.05);',
    '  --tile-shadow: 0 2px 0 rgba(16, 24, 40, 0.05), 0 1px 3px rgba(16, 24, 40, 0.06);',
    '  --hero-glow-a: rgba(37, 99, 235, 0.10);',
    '  --hero-glow-b: rgba(8, 123, 96, 0.09);',
    '  --hero-glow-c: rgba(245, 158, 11, 0.08);'
  ].join('\n');
  const darkElevation = [
    '  --glass-bg: rgba(13, 17, 23, 0.80);',
    '  --glass-border: rgba(240, 245, 255, 0.09);',
    '  --card-border: rgba(240, 245, 255, 0.09);',
    '  --shadow-xs: 0 1px 2px rgba(0, 0, 0, 0.35);',
    '  --shadow-sm: 0 4px 12px rgba(0, 0, 0, 0.32);',
    '  --shadow-md: 0 18px 40px -14px rgba(0, 0, 0, 0.55);',
    '  --shadow-stage: 0 32px 72px -18px rgba(0, 0, 0, 0.68), 0 0 0 1px rgba(240, 245, 255, 0.06);',
    '  --tile-shadow: 0 2px 0 rgba(0, 0, 0, 0.38), inset 0 1px 0 rgba(255, 255, 255, 0.04);',
    '  --hero-glow-a: rgba(120, 180, 241, 0.14);',
    '  --hero-glow-b: rgba(147, 217, 195, 0.10);',
    '  --hero-glow-c: rgba(232, 184, 90, 0.09);'
  ].join('\n');
  return `/* Generated by npm run build from style/tokens.json. */
:root {
${colors('light')}
${lightElevation}
${dimensions.join('\n')}
${typography.join('\n')}
  --surface: var(--surface-strong);
  --font-sans: ${tokens.type.families.sans};
}
@media (prefers-color-scheme: dark) {
  :root {
${colors('dark')}
${darkElevation}
  }
}
html[data-theme] {
${colors('light')}
${lightElevation}
}
html[data-theme="night"] {
${colors('dark')}
${darkElevation}
}
`;
}
